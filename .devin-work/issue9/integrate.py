GOJU = "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"
def goju_key(kana):
    return [GOJU.find(c) if GOJU.find(c)>=0 else 99 for c in kana.strip()]

def rows_of(text):
    """テーブル行から (用語, 読み列, 所在節) を抽出。
    表形状は直近のヘッダ行で判定：「用語」表→cells[1]/[2]、「体系」表→cells[1]+読みなし。
    その他の表（収録外一覧等）は収集しない。末尾 `|` の有無で要素数がずれるため列数は見ない。"""
    out, cur, mode = [], "?", None
    for line in text.splitlines():
        if line.startswith("#"):
            m = re.match(r"^#+\s*([\d.]+[a-zA-Z\-]*)", line)
            if m: cur = m.group(1)
            mode = None
        elif line.startswith("|") and not line.startswith("|---"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if cells[0] == "用語": mode = "term"; continue
            if cells[0] == "体系": mode = "sys"; continue
            if cells[0] in ("棚卸し語", "ID", "対象", "区分"): mode = None; continue
            if mode == "term" and len(cells) >= 6:
                out.append((cells[0], cells[1], cur))
            elif mode == "sys" and len(cells) >= 5:
                out.append((cells[0], "—", cur))
    return out

