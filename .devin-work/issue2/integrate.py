# ============ §1 総覧表の生成（各章別一覧の機械的合併） ============
def extract_rows(text, header_after):
    """header_after の位置以降で最初の | 名称 | テーブルの行を返す"""
    i = text.find(header_after)
    sub = text[i:]
    rows = []
    started = False
    for line in sub.split("\n"):
        if line.startswith("| 名称 "):
            started = True
            continue
        if started:
            if line.startswith("|---"):
                continue
            if line.startswith("|"):
                rows.append(line.strip())
            else:
                break
    return rows

